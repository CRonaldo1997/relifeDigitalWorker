// Active locale — defaults to Simplified Chinese; overridden by loadLocale() at boot.
let _locale = LOCALES.zh;

/**
 * Resolve an incoming locale tag to a known LOCALES key.
 * Always returns 'zh' for this simplified version.
 * @param {string} lang
 * @returns {string}
 */
function resolveLocale(lang) {
  return 'zh';
}

/**
 * Resolve locale with precedence:
 * 1) primary (typically server setting)
 * 2) fallback (typically localStorage)
 * 3) Simplified Chinese
 * @param {string} primary
 * @param {string} fallback
 * @returns {string}
 */
function resolvePreferredLocale(primary, fallback) {
  return 'zh';
}

/**
 * Translate a key.
 * @param {string} key
 * @param {...*} args - forwarded to function-valued translations
 * @returns {string}
 */
function t(key, ...args) {
  const val = _locale[key];
  if (val === undefined) return key;  // final fallback: return key itself
  return typeof val === 'function' ? val(...args) : val;
}

/**
 * Switch locale by language code.
 * Always sets to 'zh'.
 * @param {string} lang
 */
function setLocale(lang) {
  _locale = LOCALES.zh;
  localStorage.setItem('hermes-lang', 'zh');
  document.documentElement.lang = 'zh-CN';
}

/**
 * Load locale from localStorage.
 */
function loadLocale() {
  setLocale('zh');
}

/**
 * Re-stamp all [data-i18n] elements in the DOM with the current locale.
 */
function applyLocaleToDOM() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val && val !== key) el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const val = t(key);
    if (val && val !== key) el.title = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    if (val && val !== key) el.placeholder = val;
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    const val = t(key);
    if (val && val !== key) el.setAttribute('aria-label', val);
  });
  if (typeof syncAppTitlebar === 'function') syncAppTitlebar();
}

